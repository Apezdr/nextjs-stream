/**
 * The file-server URLs the sync writes, and the one function that builds them.
 *
 * A payload's paths are what the processor publishes: server-relative,
 * percent-encoded, and already under the server's prefix (its PREFIX_PATH),
 * e.g. `/media/movies/Some%20Movie%20(2020)/poster.jpg?hash=…`. A path's URL
 * is the server's baseURL followed by the path. Nothing is added between the
 * two and nothing in the path is encoded or decoded: the stored URLs, and the
 * normalizedVideoId derived from a video's, depend on these bytes.
 *
 * An absolute URL (http:// or https://) is already a URL and is kept as it
 * is: a pending auto-caption's track on the processor, for one.
 */

import { NetworkError, type ServerConfig } from '../../core/types'

/**
 * The URL of a file on a file server, from a path a payload carries.
 *
 * One `/` joins the two: a trailing one on the baseURL and the leading ones on
 * the path are dropped first.
 *
 * @throws NetworkError when there is no path, or the server has no baseURL
 */
export function fileServerUrl(path: string, server: Pick<ServerConfig, 'baseUrl'>): string {
  if (typeof path !== 'string' || path === '') {
    throw new NetworkError('A file server path is required')
  }
  if (path.startsWith('http://') || path.startsWith('https://')) return path
  if (!server?.baseUrl) {
    throw new NetworkError(`No file server baseURL for path ${path}`)
  }
  const baseUrl = server.baseUrl.endsWith('/') ? server.baseUrl.slice(0, -1) : server.baseUrl
  return `${baseUrl}/${path.replace(/^\/+/, '')}`
}

/**
 * A path under the server's media root as the processor would publish it: the
 * server's prefix, then the path. Only for a path the sync puts together
 * itself; a payload's own paths carry the prefix already.
 */
export function prefixedPath(path: string, server: Pick<ServerConfig, 'prefix'>): string {
  if (!server.prefix) return path
  const prefix = server.prefix.startsWith('/') ? server.prefix : `/${server.prefix}`
  return `${prefix.endsWith('/') ? prefix.slice(0, -1) : prefix}${path}`
}

/**
 * The stored `captionURLs` map (keyed by display language) from a payload's
 * `subtitles`, for movies and TV episodes alike.
 *
 * A completed auto-caption (`.auto.srt`) is a relative path like any other
 * subtitle and gets the server's URL; a pending one ships an absolute track URL
 * on the processor, which is kept as it is. Do not key this on `autoGenerated`:
 * a completed auto-caption is `autoGenerated: true` with a relative path, and
 * leaving it relative made the player's fetch throw `Failed to parse URL`.
 *
 * @returns null when no entry has a URL
 * @throws NetworkError when an entry's url is not a usable path
 */
export function captionUrls(
  subtitlesData: Record<string, any> | null | undefined,
  server: Pick<ServerConfig, 'id' | 'baseUrl'>
): Record<string, any> | null {
  if (!subtitlesData || typeof subtitlesData !== 'object') return null

  const out: Record<string, any> = {}
  for (const [langName, subtitle] of Object.entries(subtitlesData)) {
    if (!subtitle || typeof subtitle !== 'object' || !subtitle.url) continue

    out[langName] = {
      srcLang: subtitle.srcLang,
      url: fileServerUrl(subtitle.url, server),
      // Left out, not set to undefined, when the file server sends none (a
      // pending auto-caption stub has no file yet): MongoDB would store the
      // undefined as null and the entry would read back as different.
      ...(subtitle.lastModified !== undefined && subtitle.lastModified !== null
        ? { lastModified: subtitle.lastModified }
        : {}),
      sourceServerId: server.id,
      ...(subtitle.autoGenerated ? { autoGenerated: true } : {}),
      ...(subtitle.pending ? { pending: true } : {}),
    }
  }

  return Object.keys(out).length > 0 ? out : null
}
